const fs = require("node:fs");
const path = require("node:path");
const { parse } = require("yaml");

/**
 * The words the Help and Integrations share cards draw, written into
 * `lib/og-cards.gen.ts` (run: `node og-cards.config.js`). A card is drawn on
 * request by the Worker, which can't read `content/` (a card that read the
 * .mdx files was a 500 on saroh.in, 27 Oct 2026); `og-cards.test.ts` fails
 * when this file is behind the articles.
 */
const FENCE = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/;
const OUT = path.join(__dirname, "lib/og-cards.gen.ts");

function frontmatter(dir) {
    return fs
        .readdirSync(dir)
        .filter((f) => f.endsWith(".mdx"))
        .sort()
        .map((f) => {
            const m = FENCE.exec(fs.readFileSync(path.join(dir, f), "utf8"));
            if (!m) throw new Error(`${dir}/${f}: no frontmatter`);
            return parse(m[1]);
        });
}

function build() {
    const help = Object.fromEntries(
        frontmatter(path.join(__dirname, "content/help")).map((d) => [
            d.slug,
            { area: d.area, title: d.title },
        ]),
    );
    const integrations = Object.fromEntries(
        frontmatter(path.join(__dirname, "content/integrations")).map((d) => [
            d.slug,
            { name: d.name, intro: d.intro },
        ]),
    );
    return `// Generated by og-cards.config.js — do not edit.\nexport const HELP_CARDS: Record<string, { area: string; title: string } | undefined> = ${JSON.stringify(help, null, 4)};\n\nexport const INTEGRATION_CARDS: Record<string, { name: string; intro: string } | undefined> = ${JSON.stringify(integrations, null, 4)};\n`;
}

if (require.main === module) {
    fs.writeFileSync(OUT, build());
    console.log(`[og-cards] wrote ${path.relative(__dirname, OUT)}`);
}

module.exports = { build, OUT };
