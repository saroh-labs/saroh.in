/** An Unsplash photo at 1600 wide, credited. */
function photo(
    id: string,
    height: number,
    alt: string,
    creditName: string,
    username: string,
): DemoPhoto {
    return {
        url: `https://images.unsplash.com/photo-${id}?w=1600&q=80&auto=format&fit=crop`,
        alt,
        width: 1600,
        height,
        creditName,
        creditUrl: `https://unsplash.com/@${username}`,
    };
}

/** Variants of a made-to-order jar: stock is not counted. */
function madeToOrder(
    sku: string,
    rows: [title: string, code: string, price: string][],
): DemoVariant[] {
    return rows.map(([title, code, price]) => ({
        title,
        sku: `${sku}-${code}`,
        price,
        mrp: null,
        stock: 0,
        image: null,
    }));
}

