/** Weddings and festivals in Jaipur: busier days at the salon. */
function noorSeason(iso: string): number {
    const md = iso.slice(5);
    if (md >= "11-15" || md <= "02-15") return 1.35; // wedding season
    if (md >= "10-20" && md < "11-15") return 1.3; // Karwa Chauth, Dhanteras, Diwali
    if (md >= "04-15" && md <= "05-31") return 1.15; // summer weddings
    if (md >= "08-05" && md <= "08-20") return 1.2; // Teej
    if (md >= "07-01" && md <= "07-31") return 0.9; // monsoon lull
    return 1;
}

