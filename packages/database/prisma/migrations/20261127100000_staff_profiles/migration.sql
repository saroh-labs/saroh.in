-- Staff profiles and the Account manager console role (DEC-169, admin
-- console redesign U18). A teammate's record on the console's Team: their
-- job, contact, reporting line, capacity, manager code, commission flag, a
-- sealed tax id and an emergency contact. Saroh's, not a business's, so it
-- has no organizationId and no row-level policy (rls-coverage.test.ts lists
-- it in NOT_TENANT_OWNED).

-- CreateTable
CREATE TABLE "StaffProfile" (
    "id" TEXT NOT NULL,
    "platformAdminId" TEXT NOT NULL,
    "worksAs" TEXT NOT NULL,
    "workEmail" TEXT,
    "phone" TEXT,
    "city" TEXT,
    "languages" TEXT[] DEFAULT ARRAY[]::TEXT[],
    "joinedOn" DATE,
    "reportsToPlatformAdminId" TEXT,
    "engagement" TEXT,
    "capacity" INTEGER,
    "managerCode" TEXT NOT NULL,
    "onCommission" BOOLEAN NOT NULL DEFAULT false,
    "taxIdCiphertext" TEXT,
    "taxIdIv" TEXT,
    "taxIdAuthTag" TEXT,
    "emergencyContact" TEXT,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "StaffProfile_pkey" PRIMARY KEY ("id"),
    -- The job, separate from the console role (staff-profile.ts STAFF_JOBS).
    CONSTRAINT "StaffProfile_worksAs_check" CHECK (
        "worksAs" IN ('ACCOUNT_MANAGER_JOB', 'FINDS_BUSINESSES', 'OTHER')
    ),
    -- staff-profile.ts STAFF_ENGAGEMENTS.
    CONSTRAINT "StaffProfile_engagement_check" CHECK (
        "engagement" IS NULL
        OR "engagement" IN ('FULL_TIME', 'PART_TIME', 'FREELANCE')
    ),
    CONSTRAINT "StaffProfile_capacity_check" CHECK (
        "capacity" IS NULL OR "capacity" > 0
    ),
    -- Generated by the API from an alphabet without look-alike characters
    -- (no 0, 1, I, L or O), so an owner can read it out and type it.
    CONSTRAINT "StaffProfile_managerCode_check" CHECK (
        "managerCode" ~ '^[2-9A-HJKMNP-Z]{8}$'
    ),
    -- A sealed tax id is all three parts or none.
    CONSTRAINT "StaffProfile_taxId_sealed_check" CHECK (
        ("taxIdCiphertext" IS NULL AND "taxIdIv" IS NULL AND "taxIdAuthTag" IS NULL)
        OR ("taxIdCiphertext" IS NOT NULL AND "taxIdIv" IS NOT NULL AND "taxIdAuthTag" IS NOT NULL)
    ),
    -- Nobody reports to themselves.
    CONSTRAINT "StaffProfile_reportsTo_not_self_check" CHECK (
        "reportsToPlatformAdminId" IS NULL
        OR "reportsToPlatformAdminId" <> "platformAdminId"
    )
);

