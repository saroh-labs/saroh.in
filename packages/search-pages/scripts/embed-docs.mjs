// Embeds the GST pages', guides' and downloads' words (content/<kind>/*.mdx,
// the kinds in kinds.js) in src/docs-content.gen.ts, apart from
// content.gen.ts, with each download's file names and sizes (never the
// files themselves). Like content.gen.ts, so the pages load without a file
// system (Workers).
// Run after editing a page: pnpm --filter @saroh/search-pages docs-content
// (src/docs-load.test.ts fails while the embedded copy is stale.)
//
// `embeddedDocs({ live })` keeps only the pages whose address is in `live`
// (and only their files): saroh.in's production prebuild writes its own
// copy that way, so a draft's words never reach the site (plan
// 2026-10-31-002, U3).
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
/** @type {import("../kinds").DocKind[]} */
const DOC_KINDS = createRequire(import.meta.url)("../kinds.js").DOC_KINDS;

/** @param {string} dir */
const mdx = (dir) =>
    readdirSync(dir)
        .filter((f) => f.endsWith(".mdx"))
        .sort()
        .map((f) => f.slice(0, -4));

/**
 * @param {{ live?: readonly string[]; typesFrom?: string }} [opts] `live`: the
 *   live page addresses, every page when left out; `typesFrom`: where the
 *   generated file imports its types from (saroh.in's copy names the package)
 * @returns {string} the generated file's text
 */
export function embeddedDocs({ live, typesFrom = "./docs-load" } = {}) {
    /** @param {import("../kinds").DocKind} kind @param {string} slug */
    const keep = (kind, slug) => !live || live.includes(`/${kind.id}/${slug}`);
    const sources = DOC_KINDS.map((kind) => {
        const dir = path.join(root, "content", kind.content);
        const rows = mdx(dir)
            .filter((slug) => keep(kind, slug))
            .map(
                (slug) =>
                    `        ${JSON.stringify(slug)}: ${JSON.stringify(readFileSync(path.join(dir, `${slug}.mdx`), "utf8"))},`,
            );
        return `    ${kind.id}: {\n${rows.join("\n")}\n    },`;
    });
    const downloads = DOC_KINDS.find((k) => k.id === "downloads");
    if (!downloads) throw new Error("kinds.js has no downloads");
    const filesDir = path.join(root, "content", downloads.content, "files");
    const files = readdirSync(filesDir)
        .filter(
            (slug) =>
                keep(downloads, slug) &&
                statSync(path.join(filesDir, slug)).isDirectory(),
        )
        .sort()
        .map((slug) => {
            const dir = path.join(filesDir, slug);
            const sizes = readdirSync(dir)
                .filter((f) => !f.startsWith("."))
                .sort()
                .map(
                    (f) =>
                        `${JSON.stringify(f)}: ${statSync(path.join(dir, f)).size}`,
                );
            return `    ${JSON.stringify(slug)}: { ${sizes.join(", ")} },`;
        });
    return `// Generated by scripts/embed-docs.mjs from content/{${DOC_KINDS.map((k) => k.content).join(",")}}. Do not edit.\n\nimport type { DocFiles, DocSources } from "${typesFrom}";\n\nexport const DOC_SOURCES: DocSources = {\n${sources.join("\n")}\n};\n\nexport const DOC_FILES: DocFiles = {\n${files.join("\n")}\n};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    writeFileSync(
        path.join(root, "src", "docs-content.gen.ts"),
        embeddedDocs(),
    );
    console.log("src/docs-content.gen.ts written");
}
