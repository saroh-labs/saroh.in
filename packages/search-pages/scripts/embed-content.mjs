// Embeds content/for/*.mdx and content/tools/*.mdx in src/content.gen.ts, so
// the pages load without a file system: the admin preview runs on
// Cloudflare Workers, where there is none at request time, and no eval to
// compile MDX with either.
// Run after editing a page: pnpm --filter @saroh/search-pages content
// (src/load.test.ts fails while the embedded copy is stale.)
//
// `embedded({ live })` keeps only the pages whose address is in `live`:
// saroh.in's production prebuild writes its own copy that way, so a draft
// /for/ page's or tool's words never reach the site (plan 2026-11-01-001,
// U2), as `embeddedDocs` does for the GST pages, guides and downloads.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

/**
 * @param {"for" | "tools"} kind
 * @param {readonly string[] | undefined} live
 */
function rows(kind, live) {
    const dir = path.join(root, "content", kind);
    const files = readdirSync(dir)
        .filter((f) => f.endsWith(".mdx"))
        .filter((f) => !live || live.includes(`/${kind}/${f.slice(0, -4)}`))
        .sort();
    return files
        .map(
            (f) =>
                `    ${JSON.stringify(f.slice(0, -4))}: ${JSON.stringify(readFileSync(path.join(dir, f), "utf8"))},`,
        )
        .join("\n");
}

/**
 * @param {{ live?: readonly string[] }} [opts] `live`: the live page
 *   addresses (/for/<slug>, /tools/<slug>), every page when left out
 * @returns {string} the generated file's text
 */
export function embedded({ live } = {}) {
    return `// Generated by scripts/embed-content.mjs from content/for/*.mdx and content/tools/*.mdx. Do not edit.\n\nexport const SOURCES: Record<string, string> = {\n${rows("for", live)}\n};\n\nexport const TOOL_SOURCES: Record<string, string> = {\n${rows("tools", live)}\n};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    writeFileSync(path.join(root, "src", "content.gen.ts"), embedded());
    console.log("src/content.gen.ts written");
}
