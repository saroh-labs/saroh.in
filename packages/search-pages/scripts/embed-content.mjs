// Embeds content/for/*.mdx in src/content.gen.ts, so the pages load without a
// file system: the admin preview runs on Cloudflare Workers, where there is
// none at request time, and no eval to compile MDX with either.
// Run after editing a page: pnpm --filter @saroh/search-pages content
// (src/load.test.ts fails while the embedded copy is stale.)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "content", "for");

export function embedded() {
    const files = readdirSync(dir).filter((f) => f.endsWith(".mdx")).sort();
    const rows = files.map(
        (f) => `    ${JSON.stringify(f.slice(0, -4))}: ${JSON.stringify(readFileSync(path.join(dir, f), "utf8"))},`,
    );
    return `// Generated by scripts/embed-content.mjs from content/for/*.mdx. Do not edit.\n\nexport const SOURCES: Record<string, string> = {\n${rows.join("\n")}\n};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    writeFileSync(path.join(root, "src", "content.gen.ts"), embedded());
    console.log("src/content.gen.ts written");
}
